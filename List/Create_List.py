# Part 2: Accessing Elements (Data Nikalna)


fruits = ["Apple", "Banana", "Mango", "Cherry"]

# Positive Indexing (Aage se: 0, 1, 2...)
print(fruits[0])  # Output: Apple
print(fruits[2])  # Output: Mango

# Negative Indexing (Peeche se: -1, -2...)
print(fruits[-1]) # Output: Cherry (Aakhri item)

# Slicing [start : stop] -> stop index include nahi hota
print(fruits[1:3]) # Output: ['Banana', 'Mango']


